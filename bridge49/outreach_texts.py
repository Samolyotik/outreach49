#: Сфера, к которой привязаны все тексты этого модуля.
#:
#: Оба жанра выше говорят про подбор и привоз авто из-за границы — это не
#: настройка, а сам текст. Значит человек, ответивший на такое сообщение,
#: отвечает на разговор о конкретной сфере, и знать её мы можем без вопросов.
#:
#: Константа живёт здесь, а не у автовыдачи, нарочно: тот, кто однажды
#: перепишет тексты под другую нишу, увидит её строкой ниже. В соседнем файле
#: он бы её не нашёл, и сфера разъехалась бы с текстом молча — а цена этому
#: доступ в чужую тестовую группу, который отзывается только руками.
SECTOR_ID = "auto_import_dealers"


def sector_of_first_touch(username: str, text: str) -> str:
    """Наша ли это заготовка и к какой сфере она привязана.

    Проверка точная, а не по приметам: тексты собираются детерминированно из
    хеша адресата, поэтому по нику восстанавливается ровно та строка, которая
    ему ушла. Совпало посимвольно — сообщение точно наше и точно из этой
    полосы. Не совпало — молчим и не гадаем: похожие слова про авто мог
    написать и человек, и прежний владелец аккаунта.

    Сверяемся со всеми поколениями наборов, а не только с текущим: письма,
    ушедшие первым поколением, живут в диалогах и после смены текстов.

    Регистр ника значим: `auto_from_ko_rea` и `Auto_from_ko_rea` дают разные
    варианты. Поэтому сверяем с тем ником, что сохранён у контакта, а не с
    приведённым к нижнему регистру.
    """
    seed = (username or "").strip().lstrip("@")
    body = (text or "").strip()
    if not seed or not body:
        return ""
    известные = (channel_dm(seed), chat_message(seed),
                 _v1_channel_dm(seed), _v1_chat_message(seed))
    return SECTOR_ID if body in известные else ""


def validate(text: str, *, kind: str) -> list[str]:
    """Что не так с готовым текстом. Пустой список — всё в порядке.

    Проверка отдельная от сборки: куски пишет человек, а ошибиться можно и в
    куске. Дешевле поймать здесь, чем в чужом чате.
    """
    problems: list[str] = []
    body = (text or "").strip()
    if not body:
        problems.append("пустой текст")
        return problems
    if len(body) > MAX_LENGTH:
        problems.append(f"длиннее {MAX_LENGTH} символов")
    if _BRAND_RE.search(body):
        # В первом касании названия нет намеренно: оно превращает вопрос в
        # рекламу, а в публичном чате это повод для бана.
        problems.append("названо имя сервиса")
    if _LINK_RE.search(body):
        problems.append("есть ссылка или упоминание")
    questions = body.count("?")
    if kind == "chat" and not 1 <= questions <= 2:
        problems.append(f"вопросов {questions}, нужно один или два")
    if kind == "channel" and questions > 1:
        problems.append(f"вопросов {questions}, нужно не больше одного")
    if kind == "channel" and not body.startswith("Здравствуйте"):
        problems.append("письмо владельцу без приветствия")
    return problems


def combinations(kind: str) -> int:
    if kind == "chat":
        return (len(_CHAT_OPENINGS) * len(_CHAT_NEEDS)
                * len(_CHAT_CLOSERS) * len(_CHAT_LAYOUTS))
    return (len(_DM_GREETING) * len(_DM_WHAT)
            * len(_DM_WHY) * len(_DM_OFFER))
