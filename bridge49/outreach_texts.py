#: Чего в тексте быть не должно ни в одном жанре.
_BRAND_RE = re.compile(r"тг\s*радар|tg\s*radar|радар", re.IGNORECASE)
_LINK_RE = re.compile(r"https?://|t\.me/|@[a-z0-9_]{3,}", re.IGNORECASE)

MAX_LENGTH = 400


def _pick(options: tuple[str, ...], seed: str, salt: str) -> str:
    digest = hashlib.sha256(f"{salt}|{seed}".encode("utf-8")).digest()
    return options[int.from_bytes(digest[:8], "big") % len(options)]


def chat_message(seed: str) -> str:
    """Вопрос в публичный чат от лица человека, которому нужна услуга."""
    opening = _pick(_CHAT_OPENINGS, seed, "чат-начало")
    closer = _pick(_CHAT_CLOSERS, seed, "чат-конец")
    # Начало и конец бывают утверждениями, и на части сочетаний вопрос
    # исчезал вовсе: «Ищу, кто занимается… Буду благодарен за контакты.» —
    # это уже не вопрос участникам, а объявление. Тогда конец берём
    # вопросительный.
    if "?" not in opening and "?" not in closer:
        closer = _pick(_CHAT_QUESTION_CLOSERS, seed, "чат-вопрос")
    # Абзацами, а не в строку: так уходили сегодняшние сообщения, и в
    # Telegram три предложения подряд читаются хуже двух абзацев.
    return "\n\n".join(filter(None, (
        opening, " ".join(filter(None, (
            _pick(_CHAT_NEEDS, seed, "чат-суть"), closer))),
    )))


def channel_dm(seed: str) -> str:
    """Предложение владельцу канала показать, что находится по его теме."""
    return " ".join(filter(None, (
        _pick(_DM_WHAT, seed, "канал-что"),
        _pick(_DM_WHY, seed, "канал-почему"),
        _pick(_DM_OFFER, seed, "канал-оффер"),
    )))



def validate(text: str, *, kind: str) -> list[str]:
    """Что не так с готовым текстом. Пустой список — всё в порядке.

    Проверка отдельная от сборки: куски пишет человек, а ошибиться можно и в
    куске. Дешевле поймать здесь, чем в чужом чате.
    """
    problems: list[str] = []
    body = (text or "").strip()
    if not body:
        problems.append("пустой текст")
        return problems
    if len(body) > MAX_LENGTH:
        problems.append(f"длиннее {MAX_LENGTH} символов")
    if _BRAND_RE.search(body):
        # В первом касании названия нет намеренно: оно превращает вопрос в
        # рекламу, а в публичном чате это повод для бана.
        problems.append("названо имя сервиса")
    if _LINK_RE.search(body):
        problems.append("есть ссылка или упоминание")
    questions = body.count("?")
    if kind == "chat" and not 1 <= questions <= 2:
        problems.append(f"вопросов {questions}, нужно один или два")
    if kind == "channel" and questions > 1:
        problems.append(f"вопросов {questions}, нужно не больше одного")
    if kind == "channel" and not body.startswith("Здравствуйте"):
        problems.append("письмо владельцу без приветствия")
    return problems


def combinations(kind: str) -> int:
    if kind == "chat":
        return len(_CHAT_OPENINGS) * len(_CHAT_NEEDS) * len(_CHAT_CLOSERS)
    return len(_DM_WHAT) * len(_DM_WHY) * len(_DM_OFFER)
