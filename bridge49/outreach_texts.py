def _pick(options: tuple[str, ...], seed: str, salt: str) -> str:
    digest = hashlib.sha256(f"{salt}|{seed}".encode("utf-8")).digest()
    return options[int.from_bytes(digest[:8], "big") % len(options)]


def chat_message(seed: str) -> str:
    """Вопрос в публичный чат от лица человека, которому нужна услуга."""
    opening = _pick(_CHAT_OPENINGS, seed, "чат-начало")
    closer = _pick(_CHAT_CLOSERS, seed, "чат-конец")
    # Начало и конец бывают утверждениями, и на части сочетаний вопрос
    # исчезал вовсе: «Ищу, кто занимается… Буду благодарен за контакты.» —
    # это уже не вопрос участникам, а объявление. Тогда конец берём
    # вопросительный.
    if "?" not in opening and "?" not in closer:
        closer = _pick(_CHAT_QUESTION_CLOSERS, seed, "чат-вопрос")
    tail = " ".join(filter(None, (
        _pick(_CHAT_NEEDS, seed, "чат-суть"), closer)))
    if _pick(_CHAT_LAYOUTS, seed, "чат-раскладка") == "одним":
        return " ".join(filter(None, (opening, tail)))
    return "\n\n".join(filter(None, (opening, tail)))


