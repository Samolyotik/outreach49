"""Тексты первых касаний в чаты и в личку каналов.

Два разных жанра, и путать их нельзя.

**Публичный чат.** Мы пишем как человек, которому нужна услуга: спрашиваем
совета у участников. Это сигнал спроса, а не предложение. Реклама в чужом чате
— повод для бана, вопрос — нет.

**Личка канала.** Здесь наоборот: пишем владельцу канала и предлагаем
показать сервис. Он в нише, где спрос есть, и это ему полезно.

## Почему комбинаторика, а не модель

Текстов нужно полторы сотни за раз, они короткие и по одному шаблону. Модель
здесь дала бы разброс ценой задержки, стоимости и риска выдумать обещание,
которого мы не давали. Сложить фразу из проверенных кусков дешевле и
безопаснее: каждый кусок написан один раз и прочитан глазами.

Вариант выбирается хешем от адресата, поэтому повторный прогон даёт тот же
текст, а не новый.

## Сколько нужно вариантов

Первое поколение давало 150 комбинаций у чата и 125 у лички каналов. Расчёт
был на дневную норму в 85 сообщений, и пока её держали, совпадения были
редки. На плане 07.08 норма выросла до 188 писем в каналы — и по принципу
Дирихле шестьдесят три дубля были обеспечены ещё до сборки. По факту вышло
хуже: 188 сообщений дали 94 разных текста, один и тот же ушёл семь раз, а
трижды один аккаунт отправил одинаковое дважды за день.

Это ровно тот признак, от которого мы уходили, переводя флот с личной
переписки на каналы: одинаковая строка от разных аккаунтов в один день —
то, что антиспам Telegram видит лучше всего.

Второе поколение даёт **2 880 комбинаций у чата и 2 304 у лички каналов**.

## Чем именно расширено — и чем нет

Только перефразировками. Ни одной новой темы, ни одного нового обещания, ни
одной подробности «о себе» у покупателя в чате. Набор тем закрыт первым
поколением и остаётся прежним: подбор, привоз под ключ, проверка перед
покупкой, итоговая стоимость с доставкой и растаможкой, сроки, Корея и Китай.

Так же сознательно не добавлено: оценок чужой работы («кто действительно
возит», «честный расчёт») — они меняют тон с нейтрального вопроса на упрёк;
выдуманной биографии («опыт покупки на месте есть») — это уже не
перефразировка, а другой персонаж; тем вроде гарантии и ответственности — на
них нам нечего ответить.

Множитель добран двумя вещами, которые смысла не касаются вовсе: раскладкой
сообщения в чат (два абзаца или один — люди пишут и так, и так) и знаком в
приветствии письма владельцу.

## Старые тексты продолжают узнаваться

`sector_of_first_touch` восстанавливает отправленный текст по нику и сверяет
посимвольно — на этом держится определение сферы без вопросов человеку. Смени
наборы молча, и все, кому уже написали первым поколением, при ответе
перестанут узнаваться: сфера станет неизвестной, и автовыдача уведёт их в
демо-бота вместо готового теста. Поэтому наборы первого поколения оставлены
здесь целиком и участвуют только в узнавании.
"""
